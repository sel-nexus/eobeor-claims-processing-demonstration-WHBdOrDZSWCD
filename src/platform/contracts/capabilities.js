export const ACTION_VALUES = Object.freeze(Object.values(ACTIONS));

export const ROUTE_CAPABILITY_VALUES = Object.freeze(
  Object.values(ROUTE_CAPABILITIES),
);

const actionValues = new Set(ACTION_VALUES);
const routeCapabilityValues = new Set(ROUTE_CAPABILITY_VALUES);

/**
 * Determines whether a value belongs to the canonical permission action
 * vocabulary.
 *
 * @param {unknown} value Candidate action value.
 * @returns {boolean} Whether the value is a known action.
 */
export function isPermissionAction(value) {
  return typeof value === 'string' && actionValues.has(value);
}

/**
 * Determines whether a value is a canonical route capability name.
 *
 * @param {unknown} value Candidate route capability value.
 * @returns {boolean} Whether the value is a known route capability.
 */
export function isRouteCapability(value) {
  return typeof value === 'string' && routeCapabilityValues.has(value);
}